"""Runs the forecast benchmark and writes docs/MODEL_EVALUATION.md from REAL computed metrics."""
import sys
from datetime import date
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import pandas as pd
from mediresq import config, forecasting
from mediresq.db import Database

db = Database(config.DB_PATH)
as_of = date.fromisoformat(db.scalar("SELECT value FROM meta WHERE key='as_of'"))
rows = []
for mid, nm in db.df("SELECT medicine_id, name FROM medicines").itertuples(index=False):
    s, info = forecasting.clean_series(forecasting.load_series(db, "ALL", mid, as_of))
    ev = forecasting.evaluate_series(s)
    t = ev["table"]
    rows.append(t[t.split == "test"].assign(medicine=nm, selected=ev["best_model"]))
    print("done", nm, ev["best_model"])
allr = pd.concat(rows)
agg = allr.groupby("model")[["MAE", "RMSE", "WAPE", "WAPE@7", "WAPE@14", "WAPE@30"]].median().round(4)
best = allr.groupby("medicine").apply(lambda g: g.loc[g.WAPE.idxmin(), "model"], include_groups=False).value_counts().rename("lowest_test_WAPE_count")
md = ["# Model Evaluation (computed, not assumed)", "",
      f"Generated by `scripts/evaluate_models.py` on {len(rows)} network-level daily demand series (synthetic data, as-of {as_of}).",
      "Protocol: chronological split - fit on history up to t-60, validate on 30 days (model selection), refit to t-30, test on the final 30 days (reported here).",
      "Metrics: MAE, RMSE, WAPE (sum|error|/sum actual); WAPE@h = WAPE on the first h days of the 30-day test window.", "",
      "## Median test metrics across medicines", "", "```\n" + agg.to_string() + "\n```", "",
      "## Which model had the lowest test WAPE per medicine", "", "```\n" + best.to_string() + "\n```", "",
      "## Per-medicine test results", "", "```\n" + allr[["medicine", "model", "MAE", "RMSE", "WAPE"]].round(3).to_string(index=False) + "\n```", "",
      "## Caveats", "- Data are synthetic: patterns (weekly cycle, monsoon bump, Poisson noise) come from the generator, so these scores describe the generator, not real demand.",
      "- Selection used a validation window; the reported test window is untouched by selection, but a single 30-day test window is a small sample.",
      "- Prediction intervals in the app are assumption-based (normal residuals), not empirically calibrated."]
Path(config.ROOT / "docs" / "MODEL_EVALUATION.md").write_text("\n".join(md), encoding="utf-8")
print(agg)
